/** Low-level helpers for writing ASS (Advanced SubStation) subtitle files for libass. */
import { assTime } from '../util/time.js';

/** #RRGGBB or #RRGGBBAA (CSS-style opacity) -> ASS &HAABBGGRR */
export function assColor(hex: string, extraAlpha = 0): string {
  const h = hex.replace('#', '');
  const r = h.slice(0, 2);
  const g = h.slice(2, 4);
  const b = h.slice(4, 6);
  const opacity = h.length >= 8 ? parseInt(h.slice(6, 8), 16) : 255;
  const alpha = Math.max(0, Math.min(255, 255 - opacity + extraAlpha));
  return `&H${alpha.toString(16).padStart(2, '0').toUpperCase()}${b}${g}${r}&`.toUpperCase();
}

/** Colour without alpha, for \c \1c \3c override tags: &HBBGGRR& */
export function assColorTag(hex: string): string {
  const h = hex.replace('#', '');
  return `&H${h.slice(4, 6)}${h.slice(2, 4)}${h.slice(0, 2)}&`.toUpperCase();
}

/** Alpha for \alpha \1a \3a tags from #RRGGBBAA */
export function assAlphaTag(hex: string): string {
  const h = hex.replace('#', '');
  const opacity = h.length >= 8 ? parseInt(h.slice(6, 8), 16) : 255;
  return `&H${(255 - opacity).toString(16).padStart(2, '0').toUpperCase()}&`;
}

/** Text is literal: braces and backslashes would be read as tags. */
export function assEscape(text: string): string {
  return text.replace(/\\/g, '\u29F5').replace(/\{/g, '(').replace(/\}/g, ')').replace(/\r?\n/g, '\\N');
}

export interface AssStyle {
  name: string;
  font: string;
  size: number;
  primary: string;
  secondary?: string;
  outlineColor: string;
  back: string;
  bold?: boolean;
  borderStyle: 1 | 3;
  outline: number;
  shadow: number;
  alignment: number;
  marginL: number;
  marginR: number;
  marginV: number;
  spacing?: number;
}

export interface AssEvent {
  layer?: number;
  start: number;
  end: number;
  style: string;
  text: string;
  marginL?: number;
  marginR?: number;
  marginV?: number;
}

export function buildAss(width: number, height: number, styles: AssStyle[], events: AssEvent[]): string {
  const head = [
    '[Script Info]',
    '; Generated by vibeediting',
    'ScriptType: v4.00+',
    `PlayResX: ${width}`,
    `PlayResY: ${height}`,
    'WrapStyle: 0',
    'ScaledBorderAndShadow: yes',
    'YCbCr Matrix: TV.709',
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
  ];
  for (const s of styles) {
    head.push(
      `Style: ${s.name},${s.font},${Math.round(s.size)},${s.primary},${s.secondary ?? s.primary},${s.outlineColor},${s.back},${s.bold ? -1 : 0},0,0,0,100,100,${s.spacing ?? 0},0,${s.borderStyle},${round1(s.outline)},${round1(s.shadow)},${s.alignment},${Math.round(s.marginL)},${Math.round(s.marginR)},${Math.round(s.marginV)},1`,
    );
  }
  head.push(
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
  );
  const sorted = [...events]
    .filter((e) => e.end > e.start)
    .sort((a, b) => a.start - b.start || (a.layer ?? 0) - (b.layer ?? 0));
  for (const e of sorted) {
    head.push(
      `Dialogue: ${e.layer ?? 0},${assTime(e.start)},${assTime(e.end)},${e.style},,${Math.round(e.marginL ?? 0)},${Math.round(e.marginR ?? 0)},${Math.round(e.marginV ?? 0)},,${e.text}`,
    );
  }
  return head.join('\n') + '\n';
}

const round1 = (n: number) => Math.round(n * 10) / 10;

export const DEVANAGARI = /\p{Script=Devanagari}/u;
